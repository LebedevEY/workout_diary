import { Context } from 'grammy';

export async function helpCommand(ctx: Context) {
  const helpMessage = `
🏋️‍♂️ Дневник тренировок - Помощь

📝 Добавление упражнения:
- Нажмите "Добавить упражнение" или /add
- Выберите упражнение, введите вес и повторения

🔄 Добавление подхода:
- Нажмите "Добавить подход" или /addset
- Выберите из сегодняшних упражнений
- Подходы нумеруются автоматически

📊 История:
- /history — просмотр за дату или период
- Формат даты: ДД.ММ.ГГГГ (например: 22.07.2024)

💳 Оплата:
- /pay — записать оплату
- /remaining — проверить остаток

🎯 Базовые упражнения:
- Грудь: Жим лежа, Жим с паузами
- Ноги: Присед
- Спина: Тяга гантелей, Тяга блока
- Руки: Трицепс, Бицепс
- Создать своё: /create

Команды:
/start - Главное меню
/add - Добавить упражнение
/addset - Добавить подход
/history - История тренировок
/create - Создать упражнение
/pay - Записать оплату
/remaining - Остаток тренировок
/cancel - Отменить действие
/undo - Удалить последнюю запись
/help - Эта справка
  `.trim();

  await ctx.reply(helpMessage);
}
