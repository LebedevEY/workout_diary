import { Context } from 'grammy';

export async function helpCommand(ctx: Context) {
  const helpMessage = `
🏋️‍♂️ Дневник тренировок - Помощь

📝 Добавление упражнения:
• Нажмите кнопку "Добавить упражнение" или команду /add
• Выберите упражнение из списка
• Введите вес в килограммах
• Введите количество повторений

🔄 Добавление подхода:
• Нажмите кнопку "Добавить подход" или команду /addset
• Выберите упражнение из уже выполненных сегодня
• Введите вес и количество повторений для нового подхода
• Подходы автоматически нумеруются (1, 2, 3...)

📊 Просмотр истории:
• Нажмите кнопку "История тренировок" или команду /history
• Выберите период: сегодня, вчера, конкретная дата или период
• Для выбора даты используйте формат ГГГГ-ММ-ДД (например: 2024-07-22)

💳 Оплата тренировок:
• Нажмите кнопку "Записать оплату" или команду /pay
• Введите дату начала оплаты в формате ГГГГ-ММ-ДД (например: 2025-08-01)
• Введите количество оплаченных тренировок (целое число)
• Проверить остаток можно кнопкой "Осталось тренировок" или командой /remaining

🎯 Доступные упражнения:
• Жим лёжа, Приседания, Становая тяга
• Подтягивания, Жим стоя, Отжимания
• Сгибания на бицепс, Французский жим
• Планка, Выпады

💡 Советы:
• Все данные сохраняются автоматически
• Можно просматривать историю за любой период
• Вес указывается в килограммах
• Количество повторений - целое число

Команды:
/start - Главное меню
/add - Добавить упражнение
/addset - Добавить подход к упражнению
/history - История тренировок
/pay - Записать оплату
/remaining - Остаток тренировок
/help - Эта справка
  `.trim();

  await ctx.reply(helpMessage);
}
